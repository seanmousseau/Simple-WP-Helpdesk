#!/usr/bin/env bash
#
# Bootstrap a WordPress test environment for the wp-phpunit integration suite.
#
# Based on the canonical wp-cli scaffolded install-wp-tests.sh but trimmed
# to our specifics:
#   - WP test framework comes from the wp-phpunit/wp-phpunit composer package
#     (already installed by composer require-dev); no svn checkout needed.
#   - We only configure the test DB + wp-tests-config.php.
#
# Usage:
#   bin/install-wp-tests.sh <db_name> <db_user> <db_pass> [db_host] [wp_version]
#
# Example:
#   bin/install-wp-tests.sh wordpress_test root '' 127.0.0.1:3306 latest
#
# The DB will be DROPPED AND RECREATED — never point this at a real database.

set -euo pipefail

if [ $# -lt 3 ]; then
    cat <<EOF
Usage: $0 <db_name> <db_user> <db_pass> [db_host] [wp_version]

Required env (set via composer dev deps — do NOT override unless you know why):
  WP_TESTS_DIR   — path to wp-phpunit framework (default: vendor/wp-phpunit/wp-phpunit)

Example:
  $0 swh_phpunit_test root '' 127.0.0.1:3306
EOF
    exit 2
fi

DB_NAME="$1"
DB_USER="$2"
DB_PASS="$3"
DB_HOST="${4:-localhost}"
WP_VERSION="${5:-latest}"

REPO_ROOT="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
WP_TESTS_DIR="${WP_TESTS_DIR:-${REPO_ROOT}/vendor/wp-phpunit/wp-phpunit}"

if [ ! -d "${WP_TESTS_DIR}" ]; then
    echo "ERROR: wp-phpunit not found at ${WP_TESTS_DIR}"
    echo "  Run: composer install --dev"
    exit 1
fi

# Generate wp-tests-config.php in the integration tests dir so the bootstrap
# can find it. The file mirrors WP core's wp-tests-config-sample.php structure.
CONFIG_PATH="${REPO_ROOT}/tests/Integration/wp-tests-config.php"
cat > "${CONFIG_PATH}" <<EOF
<?php
/**
 * Generated by bin/install-wp-tests.sh — DO NOT COMMIT.
 * Local config for the wp-phpunit integration tests.
 */

define( 'ABSPATH', '${WP_TESTS_DIR}/data/wordpress/' );
define( 'WP_DEFAULT_THEME', 'default' );

define( 'WP_TESTS_DOMAIN',      'example.org' );
define( 'WP_TESTS_EMAIL',       'admin@example.org' );
define( 'WP_TESTS_TITLE',       'Test Blog' );
define( 'WP_PHP_BINARY',        'php' );

\$table_prefix = 'wptests_';
define( 'DB_NAME',     '${DB_NAME}' );
define( 'DB_USER',     '${DB_USER}' );
define( 'DB_PASSWORD', '${DB_PASS}' );
define( 'DB_HOST',     '${DB_HOST}' );
define( 'DB_CHARSET',  'utf8' );
define( 'DB_COLLATE',  '' );
EOF

echo "✓ Wrote ${CONFIG_PATH}"

# Initialise the test database. DROPS the existing DB — only point at a
# throwaway target.
if command -v mysql >/dev/null 2>&1; then
    PWFLAG=""
    if [ -n "${DB_PASS}" ]; then
        PWFLAG="-p${DB_PASS}"
    fi
    mysql -h"${DB_HOST%:*}" -P"${DB_HOST##*:}" -u"${DB_USER}" ${PWFLAG} \
        -e "DROP DATABASE IF EXISTS \`${DB_NAME}\`; CREATE DATABASE \`${DB_NAME}\` CHARACTER SET utf8 COLLATE utf8_general_ci;"
    echo "✓ Recreated DB ${DB_NAME}"
else
    echo "WARN: mysql CLI not installed. Create ${DB_NAME} manually before running tests."
fi

echo ""
echo "✓ Integration test environment ready."
echo "  Run: vendor/bin/phpunit --configuration phpunit-integration.xml"
